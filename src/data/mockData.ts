export function calculateRideFares(distanceKm: number, tripMode: 'direct' | 'round_trip' = 'direct', returnWaitMins: number = 30) {
  const dist = Math.max(1, distanceKm);
  const isRound = tripMode === 'round_trip';
  
  // Direct trip base fares
  const directBike = Math.round(25 + dist * 8);
  const directAuto = Math.round(35 + dist * 12);
  const directMini = Math.round(45 + dist * 11);
  const directHatchback = Math.round(55 + dist * 14);
  const directSedan = Math.round(75 + dist * 18);
  const directSuv = Math.round(115 + dist * 24);
  const directCarpool = Math.round(30 + dist * 6);
  const directCourier = Math.round(35 + dist * 9);

  // Round trip applies a 15% discount on the return leg (Multiplier = 1.0 + 0.85 = 1.85x)
  // Plus nominal driver wait allowance (First 30m free, +₹15 per extra 30m)
  const waitCharge = isRound ? Math.max(0, Math.floor((returnWaitMins - 30) / 30) * 15) : 0;
  const roundMultiplier = 1.85;

  const calculateFare = (base: number) => {
    if (!isRound) return base;
    return Math.round(base * roundMultiplier + waitCharge);
  };

  const calculateSavings = (base: number) => {
    if (!isRound) return 0;
    const fullTwoWay = base * 2;
    const discounted = Math.round(base * roundMultiplier + waitCharge);
    return Math.max(0, fullTwoWay - discounted);
  };

  const tripDuration = (oneWayMins: number) => {
    if (!isRound) return oneWayMins;
    return (oneWayMins * 2) + returnWaitMins;
  };

  return {
    isRoundTrip: isRound,
    tripMode,
    returnWaitMins,
    totalDistanceKm: isRound ? dist * 2 : dist,
    bike: {
      fare: calculateFare(directBike),
      directFare: directBike,
      savings: calculateSavings(directBike),
      etaMins: Math.round(2 + Math.random() * 2),
      tripMins: tripDuration(Math.round(dist * 2.2)),
    },
    auto: {
      fare: calculateFare(directAuto),
      directFare: directAuto,
      savings: calculateSavings(directAuto),
      etaMins: Math.round(3 + Math.random() * 3),
      tripMins: tripDuration(Math.round(dist * 2.8)),
    },
    cab: {
      mini: {
        fare: calculateFare(directMini),
        directFare: directMini,
        savings: calculateSavings(directMini),
        etaMins: 2,
        tripMins: tripDuration(Math.round(dist * 2.5)),
      },
      hatchback: {
        fare: calculateFare(directHatchback),
        directFare: directHatchback,
        savings: calculateSavings(directHatchback),
        etaMins: 4,
        tripMins: tripDuration(Math.round(dist * 2.5)),
      },
      sedan: {
        fare: calculateFare(directSedan),
        directFare: directSedan,
        savings: calculateSavings(directSedan),
        etaMins: 3,
        tripMins: tripDuration(Math.round(dist * 2.4)),
      },
      suv: {
        fare: calculateFare(directSuv),
        directFare: directSuv,
        savings: calculateSavings(directSuv),
        etaMins: 5,
        tripMins: tripDuration(Math.round(dist * 2.4)),
      },
    },
    self_drive: {
      hourlyStarting: 149,
      etaMins: 5,
    },
    carpooling: {
      perSeatAvg: calculateFare(directCarpool),
      directFare: directCarpool,
      savings: calculateSavings(directCarpool),
      availableRidesCount: 4,
    },
    courier: {
      startingFare: calculateFare(directCourier),
      directFare: directCourier,
      savings: calculateSavings(directCourier),
      etaMins: 3,
    },
  };
}
